import test from 'node:test';
import assert from 'node:assert/strict';
import handler from '../api/game.js';
function call(op,p={},token='',method='POST'){
 const req={method,headers:token?{authorization:'Bearer '+token}:{},body:{op,...p},query:{op,...p}};
 const res={statusCode:200,setHeader(){},status(v){this.statusCode=v;return this},json(obj){this.body=obj;return this}};
 return Promise.resolve(handler(req,res)).then(()=>({status:res.statusCode,data:res.body}));
}
test('API: negotiated payroll, project inspection and enforceable investor KPI',async()=>{
 const create=await call('createClass',{setupKey:'local-development-key',className:'Salary QA Integration',pin:'test-board-2026'});
 assert.equal(create.status,200);
 const room=create.data.room,lecturer=create.data.token;
 const join=await call('join',{room,role:'founder',group:'01',pin:'founder-2026'});
 const other=await call('join',{room,role:'founder',group:'02',pin:'other-2026'});
 assert.equal(join.status,200);assert.equal(other.status,200);
 const founder=join.data.token;
 const createStartup=await call('action',{type:'createStartup',data:{name:'CohortLab',capital:500,industry:'SaaS'}},founder);
 assert.equal(createStartup.status,200);
 const badHire=await call('action',{type:'hire',data:{role:'engineer',salary:-20,name:'Rejected'}},founder);
 assert.equal(badHire.status,400);
 const hire=await call('action',{type:'hire',data:{role:'engineer',salary:2.7,name:'Developer'}},founder);
 assert.equal(hire.status,200);
 let my=await call('state',{},founder,'GET');
 assert.equal(my.data.state.employees[0].salary,2.7);
 const worker=my.data.state.employees[0].id;
 const renegotiate=await call('action',{type:'changeSalary',data:{employee:worker,salary:17.75}},founder);
 assert.equal(renegotiate.status,200);
 my=await call('state',{},founder,'GET');
 assert.equal(my.data.state.payroll,17.75);
 const assign=await call('action',{type:'task',data:{task:'mvp',employee:worker}},founder);
 assert.equal(assign.status,200);
 const work=await call('action',{type:'week',data:{}},founder);
 assert.equal(work.status,200);
 my=await call('state',{},founder,'GET');
 assert.equal(my.data.state.tasks.length,1);
 assert.equal(my.data.state.tasks[0].weeklyReports.length,1);
 const unauthorized=await call('state',{group:'01'},other.data.token,'GET');
 assert.equal(unauthorized.data.state.company,null);
 const offer=await call('action',{type:'offer',data:{group:'01',amount:100,equity:12}},lecturer);
 assert.equal(offer.status,200);
 const pressure=await call('action',{type:'pressure',data:{group:'01',metric:'cash',target:9000,deadline:1,text:'Raise operating cash to 9000m'}},lecturer);
 assert.equal(pressure.status,200);
 const close=await call('action',{type:'advance',data:{}},lecturer);
 assert.equal(close.status,200);
 my=await call('state',{},founder,'GET');
 assert.equal(my.data.state.directives[0].status,'failed');
 assert.equal(my.data.state.fundingFrozen,true);
 const blocked=await call('action',{type:'accept',data:{offer:my.data.state.offers[0].id}},founder);
 assert.equal(blocked.status,409);
 const release=await call('action',{type:'relief',data:{group:'01'}},lecturer);
 assert.equal(release.status,200);
 const now=await call('state',{},founder,'GET');
 assert.equal(now.data.state.fundingFrozen,false);
 const approved=await call('action',{type:'accept',data:{offer:now.data.state.offers[0].id}},founder);
 assert.equal(approved.status,200);
 const lecturerView=await call('state',{group:'01'},lecturer,'GET');
 assert.equal(lecturerView.data.state.employees[0].salary,17.75);
 assert.equal(lecturerView.data.state.tasks[0].weeklyReports.length,1);
});
